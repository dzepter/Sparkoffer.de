"use client";

import { useEffect, useRef, type ElementType, type ReactNode } from "react";

/**
 * Sanftes Einblenden beim Scrollen.
 * Ohne JavaScript oder bei `prefers-reduced-motion` sind alle Inhalte
 * sofort sichtbar (siehe globals.css).
 *
 * Über `as` kann ein semantisch passendes Element gerendert werden
 * (z. B. `as="li"` innerhalb von Listen, damit das HTML gültig bleibt).
 */
export function Reveal({
  children,
  className = "",
  delay = 0,
  as: Tag = "div",
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
  as?: ElementType;
}) {
  const ref = useRef<HTMLElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      el.classList.add("is-visible");
      return;
    }
    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            el.classList.add("is-visible");
            observer.disconnect();
          }
        }
      },
      { rootMargin: "0px 0px -8% 0px" }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <Tag
      ref={ref}
      className={`reveal ${className}`}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
    >
      {children}
    </Tag>
  );
}
